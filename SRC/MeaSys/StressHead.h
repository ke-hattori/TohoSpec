class CStressHead
{
public:
	CStressHead() {::ZeroMemory(m_szErrorMessage, sizeof(m_szErrorMessage));}
	virtual ~CStressHead() {}

	virtual BOOL InitInstance()=0;
	virtual void ExitInstance()=0;

	virtual BOOL ChangeCommMode()=0;				// モード変更コマンド - 通信モードへの移行
	virtual BOOL ChangeNormalMode()=0;				// モード変更コマンド - 通常モードへの移行

	virtual BOOL ChangeProgramNo(int iNo)=0;		// 測定制御コマンド - プログラム切換
	virtual BOOL ConfirmProgramNo(int& iNo)=0;		// 測定制御コマンド - プログラム確認
	virtual BOOL InitDataStrage()=0;				// 測定制御コマンド - データストレージ初期化
	virtual BOOL StartDataStrage()=0;				// 測定制御コマンド - データストレージ開始
	virtual BOOL StopDataStrage()=0;				// 測定制御コマンド - データストレージ停止
	virtual BOOL StatusInfoDataStrage(int& iState, int& iData)=0;							// 測定制御コマンド - データストレージ・蓄積状態出力	// OUT01固定
	virtual BOOL OutputDataStrage(int iChannel, double dDataList[], int nOccurence)=0;	// 測定制御コマンド - データストレージ・データ出力
	virtual BOOL OutputDataStrage(int iChannel, CStringArray& rStringList)=0;				// 測定制御コマンド - データストレージ・データ出力
	virtual BOOL AutoZeroOn(int iChannel)=0;		// 測定制御コマンド - オートゼロON（単一）
	virtual BOOL AutoZeroOff(int iChannel)=0;		// 測定制御コマンド - オートゼロOFF（単一）
	virtual BOOL PanelLockOn()=0;					// 測定制御コマンド - パネルロックオン
	virtual BOOL PanelLockOff()=0;					// 測定制御コマンド - パネルロックオフ
	virtual BOOL Send(LPCTSTR pszCmd)=0;
	virtual void MyMessageBox(HWND hWnd, LPCTSTR lpText, LPCTSTR lpCaption, UINT uType)
	{
		_tcscpy(m_szErrorMessage, lpText);
		::MessageBox(hWnd, lpText, lpCaption, uType);
	}
	virtual LPCTSTR GetLastError() {return m_szErrorMessage;}

protected:
	TCHAR m_szErrorMessage[256];
};

